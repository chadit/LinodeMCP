_UPDATE = "update"
_REFUSE = "refuse"
_HOLD = "hold"
_FLOAT = "float"
_UNKNOWN = "unknown"

_CODEGEN_REASON = (
    "codegen must stay byte-reproducible and every committed baseline was"
    " captured under this version"
)

# Tool versions that decide generated bytes. Bumping one moves the baselines
# instead of the code, so the buf pin and the plugins it drives are refused.
_PROTECTED_TOOLS = {
    "github.com/bufbuild/buf/cmd/buf": _CODEGEN_REASON,
    "buf.build/protocolbuffers/go": _CODEGEN_REASON,
    "buf.build/protocolbuffers/python": _CODEGEN_REASON,
    "buf.build/protocolbuffers/pyi": _CODEGEN_REASON,
}

# Python floors that answer to something other than "whatever released last".
_PROTECTED_PYTHON = {
    "protobuf": (
        "its floor tracks the buf python and pyi plugin tags in buf.gen.yaml;"
        " move the two together or every _pb2 import raises"
    ),
    "protovalidate": (
        "pinned exactly: the generated buf/validate messages come from this release"
    ),
}

_FLOAT_NOTE = "no declared version, so every run resolves the newest release"
_RUNTIME_NOTE = "resolved from the newest release at install time"
_PRECOMMIT_NOTE = "pre-commit autoupdate rewrites the rev"
_LOCAL_NOTE = "a path in this repository, which carries no version"
_ODD_PIN_NOTE = "a written-down version with no resolver here"
_ACTION_DIGEST_NOTE = "sha and the trailing version comment, rewritten together"
