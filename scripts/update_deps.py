#!/usr/bin/env python3
"""Refresh every dependency version this repository declares, in one command.

Five surfaces carry a declared version, and each one is found from a declared
source rather than from a path written here:

- Go modules: every language directory docs/contracts/languages.txt registers
  that carries a go.mod. `go get -u ./...` then `go mod tidy`. Every run first
  checks each go.mod require line against its own go.sum and fails when one has
  no module hash, because `go get -u` against a graph that does not resolve
  stacks a second failure on the first.
- Language versions: the `go` directive in each go.mod and `requires-python` in
  each uv project. These are reported and never rewritten. A language version
  is not a dependency; it is the floor every dependency resolves against, so it
  gets its own surface rather than one more line in a refresh diff.
- Python: every uv project, meaning a directory holding both a pyproject.toml
  and a uv.lock. That is the registered language directories plus the tool
  projects under tools/, so the comparator's own project is covered the same
  way `make tools-typecheck` covers it, and a third project arrives without an
  edit here. `uv lock --upgrade`, then the declared floors rise to what uv
  locked, then a plain `uv lock` so the requirement strings the lock records
  match the pyproject again.
- Tool versions: the provisioning surface, meaning scripts/*.sh plus the root
  Makefile and each registered language's Makefile, together with the codegen
  templates and the pre-commit hook revisions. Almost everything here floats at
  @latest by repo policy (scripts/ci-setup.sh states it), so this surface
  reports what floats, refuses the pins that must not move, and updates the
  revisions that are written down.
- GitHub Actions: every `uses:` line under .github/workflows. Renovate's
  helpers:pinGitHubActionDigests writes `owner/repo@<sha> # <tag>`, and that
  exact form is preserved: the sha and the trailing comment are rewritten
  together or the pin is wrong. The tag a pin follows is the comment, so a
  reference tracking `v7` stays on the newest `v7`-shaped tag rather than
  jumping to a three-part one.

buf is refused by name. Its version decides the bytes `make proto` writes, and
every baseline in this repository was captured under it, so a bump would move
the baselines instead of the code. The buf remote codegen plugins are refused
for the same reason.

Renovate already manages the four writable surfaces daily at 04:00 UTC with
branch automerge, so this target and Renovate write the same files. That
overlap is deliberate. It is also why every rewrite here copies Renovate's pin
form: a human diffing one against the other sees the same shape. Renovate has
custom managers for the language versions too, and it moves them where this
target only reports them.
docs/dependency-updates.md carries the rest of that story.

Nothing here touches git. The target rewrites files and stops; staging,
branching, and committing stay human work.

`--dry-run` makes no network call at all. It names every target discovery
found, the value each one declares now, and the disposition it would get, so
the plan can be read offline before anything rewrites a lock file. It cannot
name the version a bump would land on, because knowing that needs the network.

Never a `make check` gate: this needs the network and it writes. Run it via
`make update-deps` (or `make update-deps-dry-run`).

Usage: update_deps.py [--dry-run]
"""

