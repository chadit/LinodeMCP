func readGenerated(t *testing.T, dir, name string) string {
	t.Helper()

	raw, err := os.ReadFile(filepath.Join(dir, name))
	if err != nil {
		t.Fatalf("read %s: %v", name, err)
	}

	return string(raw)
}

// readNames reads one of the repo's one-name-per-line contracts.
func readNames(t *testing.T, path string) []string {
	t.Helper()

	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}

	names := make([]string, 0)

	for line := range strings.SplitSeq(string(raw), "\n") {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" || strings.HasPrefix(trimmed, "#") {
			continue
		}

		names = append(names, trimmed)
	}

	return names
}

// writeLanguages writes a languages registry naming the given languages, in
// the three-field shape docs/contracts/languages.txt carries.
//
// One run emits every registered language, so a case that reads only the Go
// tree registers only Go: pointing at the real registry would render the Python
// tree through the formatter on every one of them.
func writeLanguages(t *testing.T, names ...string) string {
	t.Helper()

	lines := make([]string, 0, len(names)+1)
	lines = append(lines, "# Registry for one test run.")

	for _, name := range names {
		lines = append(lines, name+"\t"+name+"\tdump")
	}

	path := filepath.Join(t.TempDir(), "languages.txt")
	if err := os.WriteFile(path, []byte(strings.Join(lines, "\n")+"\n"), 0o600); err != nil {
		t.Fatalf("write languages registry: %v", err)
	}

	return path
}

// writeHandwritten writes a hand-written list built from the real one.
//
// Every failure case here is a change to that list rather than a list of its
// own, because the list is now the whole surface minus the cohort: a short
// invented list would put 400-odd unrelated tools into the cohort and fail on
// whichever one the emitter reached first.
func writeHandwritten(t *testing.T, names []string) string {
	t.Helper()

	path := filepath.Join(t.TempDir(), "handwritten.txt")
	if err := os.WriteFile(path, []byte(strings.Join(names, "\n")+"\n"), 0o600); err != nil {
		t.Fatalf("write hand-written list: %v", err)
	}

	return path
}

// alsoGenerated drops one name from the hand-written list whether or not the
// list still claims it, so a case whose subject is the emitted shape keeps
// proving the same thing the day its tool moves. Its counterpart, which
// promoted a still-hand-written tool to prove a refusal, is gone: no name is
// left on the list to promote, and each case that used one now reads its rule
// off the emitted tree.
func alsoGenerated(t *testing.T, tool string) []string {
	t.Helper()

	return slices.DeleteFunc(readNames(t, handwrittenFile),
		func(name string) bool { return name == tool })
}

func runGenExpectingFailure(t *testing.T, handwritten string) string {
	t.Helper()

	cmd := exec.CommandContext(t.Context(), "go", "run", ".",
		"-languages", writeLanguages(t, "go"),
		"-handwritten", handwritten,
		"-out", t.TempDir(), "-answers-out", t.TempDir(), "-schemas", schemaDir)

	output, err := cmd.CombinedOutput()
	if err == nil {
		t.Fatalf("toolgen succeeded, want a failure:\n%s", output)
	}

	return string(output)
}

