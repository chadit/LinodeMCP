// runGen emits into a temp tree using the same invocation `make proto` uses,
// since what the build depends on is the files written, not how they are chosen.
func runGen(t *testing.T) string {
	t.Helper()

	out := t.TempDir()

	cmd := exec.CommandContext(t.Context(), "go", "run", ".",
		"-languages", writeLanguages(t, "go"),
		"-handwritten", handwrittenFile,
		"-out", out, "-answers-out", t.TempDir(), "-schemas", schemaDir)

	if output, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("toolgen failed: %v\n%s", err, output)
	}

	return out
}

// runGenFrom emits the cohort a custom hand-written list leaves, for the tools
