// A plan is neither a preview nor a gated call, so the branch answers ahead of
// both. A call that fell to either would be answered as something else.
func TestStagedBranchRunsAheadOfThePreviewAndTheGate(t *testing.T) {
	t.Parallel()

	source := readGenerated(t, runGen(t), "instance.gen.go")

	handler := "func handleLinodeInstanceResize(ctx context.Context, request *mcp.CallToolRequest, cfg *config.Config) (*mcp.CallToolResult, error) {"

	opens := strings.Index(source, handler)
	if opens < 0 {
		t.Fatal("emitted tree has no resize handler to read")
	}

	body := source[opens+len(handler):]

	staged := strings.Index(body, "twoStageLinodeInstanceResize(ctx, request, cfg)")
	preview := strings.Index(body, "tools.IsDryRun(request)")
	gate := strings.Index(body, "tools.RequireConfirm(")

	if staged < 0 || preview < 0 || gate < 0 {
		t.Fatalf("handler is missing a branch: staged=%d preview=%d gate=%d", staged, preview, gate)
	}

	if staged > preview || preview > gate {
		t.Errorf("branches are out of order: staged=%d preview=%d gate=%d", staged, preview, gate)
	}
}

// stateReadDecode and readHandlerDecode find the message each side of a
// declared fetch decodes the raw body into: the state read at a preview or a
// plan, and the read tool's own handler.
var (
	stateReadDecode   = regexp.MustCompile(`state := &linodev1\.(\w+)\{\}\n\n\s+raw, err := client\.CallProtoRouteState\w*\(ctx, "([^"]+)"`)
	readHandlerDecode = regexp.MustCompile(`response := &linodev1\.(\w+)\{\}\n\n\tif err := client\.CallProtoRoute\w*\(ctx, "([^"]+)"`)
)

// TestEveryDeclaredFetchDecodesWhatItsReadDecodes: a declared fetch calls the
// read's own route, so it has to decode that route's body the same way the read
// does. A read answering a wrapper around the resource decodes the member and
// wraps it afterwards, and a fetch that skipped the member would project the
// raw body through a message modeling none of its fields and report an empty
// state. Only two tools name a payload member today, so nothing else would
// notice a third going missing.
func TestEveryDeclaredFetchDecodesWhatItsReadDecodes(t *testing.T) {
	t.Parallel()

	dir := runGen(t)

	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("read emitted tree: %v", err)
	}

	sources := make([]string, 0, len(entries))
	for _, entry := range entries {
		sources = append(sources, readGenerated(t, dir, entry.Name()))
	}

	reads := make([][]string, 0, len(sources))
	for _, source := range sources {
		reads = append(reads, readHandlerDecode.FindAllStringSubmatch(source, -1)...)
	}

	decoded := make(map[string]string, len(reads))
	for _, match := range reads {
		decoded[match[2]] = match[1]
	}

	var fetches int

	// The three declared state forms decode through their own runtime rather
	// than the single-resource call, so each counted occurrence is one fetch.
	stateForms := regexp.MustCompile(
		`tools\.Fetch(?:CollectionScan|EnvelopeState|CompositeState)\(`,
	)
	for _, source := range sources {
		fetches += len(stateForms.FindAllString(source, -1))
	}

	for _, source := range sources {
		for _, match := range stateReadDecode.FindAllStringSubmatch(source, -1) {
			fetches++

			read := match[2]

			want, found := decoded[read]
			if !found {
				continue
			}

			if match[1] != want {
				t.Errorf("the fetch through %s decodes %s, but %s decodes %s: name the payload member",
					read, match[1], read, want)
			}
		}
	}

	// Every state route in the contract, so a scan that stopped matching cannot
	// pass by measuring nothing.
	const declaredFetches = 174

	if fetches != declaredFetches {
		t.Errorf("found %d declared fetch(es), want %d", fetches, declaredFetches)
	}
}

// envelopeStateQuery finds an envelope fetch that carries the page controls its
