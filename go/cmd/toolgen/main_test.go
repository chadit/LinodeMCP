// handlerBody scopes a check to one emitted function, so it cannot be
// satisfied by text belonging to another handler.
func handlerBody(t *testing.T, source, name string) string {
	t.Helper()

	start := strings.Index(source, "func "+name+"(")
	if start < 0 {
		t.Fatalf("emitted source declares no %s", name)
	}

	rest := source[start:]

	before, _, closed := strings.Cut(rest, "\n}\n")
	if !closed {
		return rest
	}

	return before
}

// The two branches of a mutation gate in opposite orders, and both orders
// matter. A dry run has nothing to confirm, so it validates first. A live call
// gates first, so a caller who has not confirmed learns nothing about whether
// their arguments would have been accepted.
func TestEmitsTheWriteOrderingContract(t *testing.T) {
	t.Parallel()

	source := readGenerated(t, runGen(t), "domain.gen.go")

	live := handlerBody(t, source, "handleLinodeDomainCreate")

	confirm := strings.Index(live, "tools.RequireConfirm(")
	validate := strings.Index(live, domainTypeCheck)

	if confirm < 0 || validate < 0 {
		t.Fatalf("live branch is missing a gate or a check:\n%s", live)
	}

	if confirm > validate {
		t.Errorf("live branch validates before it gates on confirm:\n%s", live)
	}

	preview := handlerBody(t, source, "previewLinodeDomainCreate")
	if strings.Contains(preview, "tools.RequireConfirm(") {
		t.Errorf("dry-run branch gates on confirm:\n%s", preview)
	}

	if !strings.Contains(preview, domainTypeCheck) {
		t.Errorf("dry-run branch skips the argument check:\n%s", preview)
	}
}

