// readRouteCall is the call a read makes and no other tier does: a mutation
// sends its body through CallProtoRouteBody, and a list runs through its own
// driver. Pairing it with the dry-run branch is what names the gated-read tier,
// where the preview comment alone would have swept in the acknowledge tier,
// which words its preview the same way.
const readRouteCall = "client.CallProtoRouteQuery("

// A read advertising a preview has to hold its fetch back behind something
// while the preview branch answers, or the dry run answers by making the call
// it previews. The confirm argument is that gate, and the emitter refuses a
// read declaring one without the other.
//
// This reads the rule off the tree rather than off a specimen: every read
// declaring dry_run now declares confirm too, so there is no tool left to drop
// from the hand-written list and be refused. The same shape the meta-answer and
// destroy state-fetch cases took when their last specimens migrated.
func TestEveryEmittedReadPreviewIsGated(t *testing.T) {
	t.Parallel()

	dir := runGen(t)

	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("read emitted tree: %v", err)
	}

	var gated int

	for _, entry := range entries {
		source := readGenerated(t, dir, entry.Name())

		for _, read := range readHandlers(source) {
			if !strings.Contains(read.body, dryRunGate) {
				continue
			}

			gated++

			confirm := strings.Index(read.body, confirmGate)
			client := strings.Index(read.body, "tools.ClientForRequest(")

			if confirm < 0 || confirm > client {
				t.Errorf("%s reaches its client without asking the gate first:\n%s", read.name, read.body)
			}
		}
	}

	// The two database credentials reads and linode_managed_credential_get, so
	// a scan that stopped finding reads cannot pass by measuring nothing.
	const gatedReads = 3

	if gated != gatedReads {
		t.Errorf("found %d gated read(s), want %d", gated, gatedReads)
	}
}

// emittedHandler is one generated handler: the name it is declared under and
// the body under it.
type emittedHandler struct {
	name string
	body string
}

// readHandlers returns every emitted read handler the source declares.
func readHandlers(source string) []emittedHandler {
	var found []emittedHandler

	for _, block := range strings.Split(source, "\nfunc handle")[1:] {
		name, _, cut := strings.Cut(block, "(")
		if !cut {
			continue
		}

		body, _, _ := strings.Cut(block, "\n}\n")
		if strings.Contains(body, readRouteCall) {
			found = append(found, emittedHandler{name: "handle" + name, body: body})
		}
	}

	return found
}

// A routeless tool lands on the meta tier and nowhere else. Every other tier
// builds a request, and a contract with no route to build one against answers
