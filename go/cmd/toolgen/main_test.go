// A meta tool answers through a declared local operation or through the
// sentence its contract declares. With neither, the emitted handler has nothing
// to return, so the emitter refuses it.
//
// This reads that refusal off the tree rather than off a specimen: every meta
// tool the contract declares now names one or the other, so there is no tool
// left to drop from the hand-written list and be refused. The same shape the
// destroy state-fetch case took when its last specimen migrated.
func TestEveryEmittedMetaToolNamesItsAnswer(t *testing.T) {
	t.Parallel()

	dir := runGen(t)

	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("read emitted tree: %v", err)
	}

	var handlers int

	for _, entry := range entries {
		source := readGenerated(t, dir, entry.Name())

		for _, handler := range metaHandlers(t, source) {
			handlers++

			if strings.Contains(handler, "tools.") {
				continue
			}

			if strings.Contains(handler, "fmt.Sprintf(") {
				continue
			}

			t.Errorf("%s emits a meta handler that answers with neither an operation nor a sentence:\n%s",
				entry.Name(), handler)
		}
	}

	// Every meta tool the contract declares, so a scan that stopped finding
	// them cannot pass by measuring nothing.
	const metaTools = 17

	if handlers != metaTools {
		t.Errorf("found %d meta handler(s), want %d", handlers, metaTools)
	}
}

// metaMarker is the sentence the emitter writes above a factory that reaches no
// Linode route, and nothing else carries it. Keying on it is what makes this
// read exactly the meta tier: matching handler bodies by their shape instead
// swept in the destroys, which reach their route through a helper rather than
// through the client call this would have filtered on.
const metaMarker = "answers from local state and reaches no Linode route"

// metaHandlers returns the body of every emitted meta handler, found through
// the factory that names it.
func metaHandlers(t *testing.T, source string) []string {
	t.Helper()

	var bodies []string

	for line := range strings.SplitSeq(source, "\n") {
		if !strings.Contains(line, metaMarker) {
			continue
		}

		factory, _, found := strings.Cut(strings.TrimPrefix(line, "// "), " builds ")
		if !found {
			t.Fatalf("meta marker on an unreadable comment: %s", line)
		}

		handler := "func handle" + strings.TrimSuffix(strings.TrimPrefix(factory, "New"), "Tool") + "("

		_, after, split := strings.Cut(source, handler)
		if !split {
			t.Fatalf("no handler named %s for the factory %s", handler, factory)
		}

		body, _, closed := strings.Cut(after, "\n}\n")
		if !closed {
			t.Fatalf("handler %s never closes", handler)
		}

		bodies = append(bodies, body)
	}

	return bodies
}

