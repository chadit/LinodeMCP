// pyLineBudget is the line length ruff holds this repo to. The emitted tree is
// linted like hand-written code, so a line the renderer cannot fit fails the
// run.
const pyLineBudget = 88

// pyHeader marks the tree as emitted rather than written, and names the emitter
// a reader would go read: one run of go/cmd/toolgen writes both languages.
const pyHeader = "# Code generated by go/cmd/toolgen. DO NOT EDIT."

// pyPackage is the import root the registry binds the cohort under.
const pyPackage = "linodemcp.gentools"

// pySuffix marks the files this renderer owns.
const pySuffix = ".py"

// The flag spellings Python writes, which are the one rendering the two
// languages cannot share: Go prints a flag as true and Python as True.
const (
	pyTrue  = "True"
	pyFalse = "False"
)

// pyUncheckedGuard opens each step of an accumulated check, which runs only
// behind whatever the rules and the readers before it already found.
const pyUncheckedGuard = "    if not message:"

// pyDocClose is the line a multi-line docstring ends on, at the one indent
// every emitted definition sits at. A constant because goconst counts the
// literal across the whole emitter, not because two renderers could spell it
// differently.
const pyDocClose = `    """`

// The two lines every driver call opens with, which every tier spells alike.
const (
	pyDriverConfigLine    = "        cfg,"
	pyDriverArgumentsLine = "        arguments,"
)

// pyArgumentsMap is the request map every emitted read and reader is handed.
const pyArgumentsMap = "arguments"

// The branch keywords an accumulated check chains its slots with.
const (
	pyBranchIf   = "if"
	pyBranchElif = "elif"
)

// pyDocIndent is how far in a docstring's body sits, and pyProseIndent how far
// in the prose a factory and a gate wrap at. Both are the columns ruff leaves
// alone, since it cannot rewrap a string literal.
const (
	pyDocIndent   = 4
	pyProseIndent = 12
)

// pyReaderSentenceIndent is how far in ruff indents a reader call's arguments
// inside a mutation's accumulated check, which is where emitted sentences sit
// deepest. A split measured shallower overflows once ruff indents it.
const pyReaderSentenceIndent = 12

